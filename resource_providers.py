"""Discovery providers for the Resource Finder.

Every result comes from a real search API or index; nothing is generated by a model. Each provider
returns plain dicts and raises ProviderError (with a user-readable message) on failures such as
rate limits, so one broken source never fails the whole search.
"""
from __future__ import annotations

import json
import os
import re
import xml.etree.ElementTree as ET
from typing import Any, Callable, Dict, List, Optional
from urllib.error import HTTPError, URLError
from urllib.parse import quote_plus, urlencode, urlparse
from urllib.request import Request, urlopen

USER_AGENT = "LectureSeekResourceFinder/1.0"
DEFAULT_TIMEOUT = 12
RESOURCE_TYPES = ("video", "paper", "book", "course", "website")

# Domains that are treated as reliable educational sources for generic web search results.
TRUSTED_DOMAINS = {
    "khanacademy.org", "coursera.org", "edx.org", "ocw.mit.edu", "mit.edu", "stanford.edu", "openstax.org",
    "class-central.com", "futurelearn.com", "udacity.com", "nature.com", "sciencedirect.com", "acm.org",
    "ieee.org", "springer.com", "britannica.com", "wikipedia.org", "arxiv.org", "jstor.org", "w3.org",
    "mathworld.wolfram.com", "geeksforgeeks.org", "developer.mozilla.org", "docs.python.org",
}
COURSE_DOMAINS = {"coursera.org", "edx.org", "ocw.mit.edu", "udacity.com", "class-central.com", "futurelearn.com",
                  "khanacademy.org", "openlearning.com", "open.edu"}


class ProviderError(RuntimeError):
    """A provider could not return results; the message is safe to show to users."""

    def __init__(self, message: str, *, rate_limited: bool = False):
        super().__init__(message)
        self.rate_limited = rate_limited


def _request(url: str, *, headers: Optional[Dict[str, str]] = None, timeout: float = DEFAULT_TIMEOUT) -> bytes:
    request = Request(url, headers={"User-Agent": USER_AGENT, **(headers or {})})
    try:
        with urlopen(request, timeout=timeout) as response:
            return response.read()
    except HTTPError as error:
        if error.code == 429:
            raise ProviderError("rate limit reached; try again later", rate_limited=True) from error
        raise ProviderError(f"service returned HTTP {error.code}") from error
    except (URLError, TimeoutError, OSError) as error:
        raise ProviderError("service is unreachable") from error


def _json(url: str, **kwargs) -> Any:
    try:
        return json.loads(_request(url, **kwargs).decode("utf-8", "replace"))
    except ValueError as error:
        raise ProviderError("service returned an unreadable response") from error


def domain_of(url: str) -> str:
    host = (urlparse(url or "").hostname or "").lower()
    return host[4:] if host.startswith("www.") else host


def is_trusted_domain(url: str) -> bool:
    host = domain_of(url)
    if not host:
        return False
    if host.endswith(".edu") or ".edu." in host or host.endswith(".gov") or ".ac." in host:
        return True
    return any(host == d or host.endswith("." + d) for d in TRUSTED_DOMAINS)


def _clean(text: Any, limit: int = 500) -> str:
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", str(text or ""))).strip()[:limit]


def _resource(kind: str, title: str, url: str, source: str, platform: str, **extra) -> Dict[str, Any]:
    return {
        "type": kind, "title": _clean(title, 300), "url": url, "source": source, "platform": platform,
        "description": extra.pop("description", ""), "published": extra.pop("published", None),
        "language": extra.pop("language", None), "authors": extra.pop("authors", []),
        "hints": extra.pop("hints", []), "popularity": extra.pop("popularity", 0), **extra,
    }


def _published(value: Any) -> Optional[str]:
    """Normalize dates to YYYY[-MM[-DD]] or None."""
    text = str(value or "").strip()
    if re.fullmatch(r"\d{8}", text):
        return f"{text[:4]}-{text[4:6]}-{text[6:]}"
    match = re.match(r"\d{4}(-\d{2}(-\d{2})?)?", text)
    return match.group(0) if match else None


# --- YouTube -----------------------------------------------------------------

def search_youtube(query: str, limit: int, *, api_key: Optional[str] = None, kind: str = "video") -> List[Dict[str, Any]]:
    """Videos (kind="video") or course playlists (kind="course")."""
    api_key = api_key if api_key is not None else os.getenv("YOUTUBE_API_KEY")
    if api_key:
        return _youtube_api(query, limit, api_key, kind)
    return _youtube_ytdlp(query, limit, kind)


def _youtube_api(query: str, limit: int, api_key: str, kind: str) -> List[Dict[str, Any]]:
    params = {"part": "snippet", "q": query, "type": "playlist" if kind == "course" else "video",
              "maxResults": max(1, min(limit, 25)), "safeSearch": "strict", "key": api_key}
    if kind == "video":
        params["videoEmbeddable"] = "true"
    data = _json("https://www.googleapis.com/youtube/v3/search?" + urlencode(params))
    results = []
    for item in data.get("items", []):
        snippet = item.get("snippet") or {}
        ident = item.get("id") or {}
        key = ident.get("playlistId") if kind == "course" else ident.get("videoId")
        if not key:
            continue
        url = f"https://www.youtube.com/playlist?list={key}" if kind == "course" else f"https://www.youtube.com/watch?v={key}"
        results.append(_resource(
            kind, snippet.get("title", ""), url, snippet.get("channelTitle") or "YouTube",
            "YouTube playlist" if kind == "course" else "YouTube",
            description=_clean(snippet.get("description")), published=_published(snippet.get("publishedAt")),
        ))
    return results


def _youtube_ytdlp(query: str, limit: int, kind: str) -> List[Dict[str, Any]]:
    try:
        import yt_dlp
    except ImportError as error:
        raise ProviderError("yt-dlp is not installed and no YOUTUBE_API_KEY is configured") from error
    if kind == "course":
        target = "https://www.youtube.com/results?search_query=" + quote_plus(query) + "&sp=EgIQAw%253D%253D"
    else:
        target = f"ytsearch{max(1, min(limit, 25))}:{query}"
    options = {"quiet": True, "no_warnings": True, "extract_flat": True, "skip_download": True,
               "socket_timeout": DEFAULT_TIMEOUT, "playlistend": limit}
    try:
        with yt_dlp.YoutubeDL(options) as ydl:
            info = ydl.extract_info(target, download=False)
    except Exception as error:
        raise ProviderError("YouTube search failed (it may be rate limiting this server)") from error
    results = []
    for entry in (info or {}).get("entries") or []:
        if not entry or not entry.get("id") or not entry.get("title"):
            continue
        is_playlist = "playlist" in str(entry.get("url", "")) or str(entry["id"]).startswith("PL")
        if (kind == "course") != is_playlist:
            continue
        url = entry.get("url") or f"https://www.youtube.com/watch?v={entry['id']}"
        results.append(_resource(
            kind, entry["title"], url, entry.get("channel") or entry.get("uploader") or "YouTube",
            "YouTube playlist" if kind == "course" else "YouTube",
            description=_clean(entry.get("description")), published=_published(entry.get("upload_date")),
            language=entry.get("language"),
            duration_seconds=entry.get("duration"), popularity=entry.get("view_count") or 0,
        ))
        if len(results) >= limit:
            break
    return results


# --- Research papers ----------------------------------------------------------

ATOM = {"a": "http://www.w3.org/2005/Atom"}


def search_arxiv(query: str, limit: int) -> List[Dict[str, Any]]:
    url = "https://export.arxiv.org/api/query?" + urlencode(
        {"search_query": f"all:{query}", "start": 0, "max_results": limit, "sortBy": "relevance"})
    try:
        root = ET.fromstring(_request(url))
    except ET.ParseError as error:
        raise ProviderError("arXiv returned an unreadable response") from error
    results = []
    for entry in root.findall("a:entry", ATOM):
        link = (entry.findtext("a:id", "", ATOM) or "").strip()
        title = _clean(entry.findtext("a:title", "", ATOM))
        if not link or not title:
            continue
        results.append(_resource(
            "paper", title, link.replace("http://", "https://"), "arXiv", "arXiv",
            description=_clean(entry.findtext("a:summary", "", ATOM), 800),
            published=_published(entry.findtext("a:published", "", ATOM)),
            authors=[_clean(a.findtext("a:name", "", ATOM), 80) for a in entry.findall("a:author", ATOM)][:5],
            hints=[c.get("term") for c in entry.findall("a:category", ATOM) if c.get("term")],
        ))
    return results


def _abstract(index: Any) -> str:
    if not isinstance(index, dict):
        return ""
    words: Dict[int, str] = {}
    for word, positions in index.items():
        for position in positions or []:
            words[position] = word
    return " ".join(words[i] for i in sorted(words))[:800]


def search_openalex(query: str, limit: int) -> List[Dict[str, Any]]:
    params = {"search": query, "per-page": limit}
    email = os.getenv("RESOURCE_FINDER_CONTACT_EMAIL")
    if email:
        params["mailto"] = email
    data = _json("https://api.openalex.org/works?" + urlencode(params))
    results = []
    for work in data.get("results", []):
        title = work.get("display_name") or work.get("title")
        location = work.get("primary_location") or {}
        url = location.get("landing_page_url") or work.get("doi") or work.get("id")
        if not title or not url:
            continue
        venue = (location.get("source") or {}).get("display_name")
        results.append(_resource(
            "paper", title, url, venue or "OpenAlex", venue or "OpenAlex",
            description=_abstract(work.get("abstract_inverted_index")),
            published=_published(work.get("publication_date")), language=work.get("language"),
            authors=[(a.get("author") or {}).get("display_name") for a in work.get("authorships", [])[:5]
                     if (a.get("author") or {}).get("display_name")],
            hints=[t.get("display_name") for t in (work.get("topics") or [])[:5] if t.get("display_name")],
            popularity=work.get("cited_by_count") or 0,
        ))
    return results


# --- Books --------------------------------------------------------------------

def search_openlibrary(query: str, limit: int) -> List[Dict[str, Any]]:
    fields = "key,title,author_name,first_publish_year,language,subject"
    data = _json("https://openlibrary.org/search.json?" + urlencode({"q": query, "limit": limit, "fields": fields}))
    results = []
    for doc in data.get("docs", []):
        if not doc.get("title") or not doc.get("key"):
            continue
        subjects = [s for s in (doc.get("subject") or [])[:8] if isinstance(s, str)]
        authors = (doc.get("author_name") or [])[:3]
        description = ("By " + ", ".join(authors) + ". " if authors else "") + (
            "Subjects: " + ", ".join(subjects) + "." if subjects else "")
        languages = doc.get("language") or []
        results.append(_resource(
            "book", doc["title"], "https://openlibrary.org" + doc["key"], "Open Library", "Open Library",
            description=description, published=_published(doc.get("first_publish_year")),
            language=languages[0] if languages else None, authors=authors, hints=subjects,
        ))
    return results


# --- Websites and courses -----------------------------------------------------

def search_wikipedia(query: str, limit: int, language: str = "en") -> List[Dict[str, Any]]:
    language = language if re.fullmatch(r"[a-z]{2,3}", language or "") else "en"
    base = f"https://{language}.wikipedia.org/w/api.php"
    data = _json(base + "?" + urlencode({
        "action": "query", "format": "json", "generator": "search", "gsrsearch": query, "gsrlimit": limit,
        "prop": "extracts|info", "exintro": 1, "explaintext": 1, "exlimit": "max", "inprop": "url"}))
    pages = sorted((data.get("query") or {}).get("pages", {}).values(), key=lambda p: p.get("index", 0))
    return [
        _resource("website", p["title"], p["fullurl"], "Wikipedia", "Wikipedia",
                  description=_clean(p.get("extract"), 600), language=language)
        for p in pages if p.get("title") and p.get("fullurl")
    ]


def search_brave(query: str, limit: int, *, api_key: Optional[str] = None) -> List[Dict[str, Any]]:
    """Optional general web search (BRAVE_SEARCH_API_KEY); only trusted educational domains are kept."""
    api_key = api_key or os.getenv("BRAVE_SEARCH_API_KEY")
    if not api_key:
        raise ProviderError("not configured (set BRAVE_SEARCH_API_KEY to enable course and website search)")
    data = _json("https://api.search.brave.com/res/v1/web/search?" + urlencode({"q": query + " course tutorial", "count": min(limit * 2, 20)}),
                 headers={"X-Subscription-Token": api_key, "Accept": "application/json"})
    results = []
    for item in (data.get("web") or {}).get("results", []):
        url = item.get("url") or ""
        if not item.get("title") or not is_trusted_domain(url):
            continue
        host = domain_of(url)
        kind = "course" if any(host == d or host.endswith("." + d) for d in COURSE_DOMAINS) else "website"
        results.append(_resource(kind, item["title"], url, host, host, description=_clean(item.get("description")),
                                 language=item.get("language"), published=_published(item.get("page_age"))))
    return results[:limit]


# Provider registry: name -> (resource types it can supply, callable(query, limit) -> results)
def default_providers(language: str = "en") -> Dict[str, Dict[str, Any]]:
    return {
        "YouTube": {"types": {"video"}, "run": lambda q, n: search_youtube(q, n, kind="video")},
        "YouTube playlists": {"types": {"course"}, "run": lambda q, n: search_youtube(q, n, kind="course")},
        "arXiv": {"types": {"paper"}, "run": search_arxiv},
        "OpenAlex": {"types": {"paper"}, "run": search_openalex},
        "Open Library": {"types": {"book"}, "run": search_openlibrary},
        "Wikipedia": {"types": {"website"}, "run": lambda q, n: search_wikipedia(q, n, language)},
        "Web search (Brave)": {"types": {"website", "course"}, "run": search_brave,
                               "enabled": lambda: bool(os.getenv("BRAVE_SEARCH_API_KEY"))},
    }


# --- Link validation -----------------------------------------------------------

def check_link(url: str, timeout: float = 6) -> str:
    """Return "ok", "broken" (definitely gone) or "unverified" (blocked, slow, or unreachable)."""
    if not re.match(r"^https?://", url or ""):
        return "broken"
    for method, extra in (("HEAD", {}), ("GET", {"Range": "bytes=0-0"})):
        request = Request(url, method=method, headers={"User-Agent": USER_AGENT, **extra})
        try:
            with urlopen(request, timeout=timeout) as response:
                return "ok" if response.status < 400 else "unverified"
        except HTTPError as error:
            if error.code in (404, 410):
                return "broken"
            if method == "HEAD" and error.code in (400, 403, 405, 501):
                continue
            return "unverified"
        except (URLError, TimeoutError, OSError, ValueError):
            return "unverified"
    return "unverified"
